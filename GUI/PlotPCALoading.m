function PlotPCALoading(ax,...
    PCAResults,...
    Wavenumbers,...
    PCNumber)
cla(ax)
plot(ax,...
    Wavenumbers,...
    PCAResults.coeff(:,PCNumber),...
    'LineWidth',1.5)
xlabel(ax,'Wavenumber (cm^{-1})')
ylabel(ax,'Loading')
title(ax,...
    sprintf('PC%d Loading',PCNumber))
axis(ax,'tight')
end