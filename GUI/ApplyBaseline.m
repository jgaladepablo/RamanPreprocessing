function Ybaseline = ApplyBaseline(X,Y,...
    smoothwidth1,bandwidth1,iterations1,...
    smoothwidth2,bandwidth2,iterations2)

[Y1,~] = f_baseline_corr(...
    X,Y,...
    smoothwidth1,...
    bandwidth1,...
    iterations1);

[Y2,~] = f_baseline_corr(...
    X,Y1,...
    smoothwidth2,...
    bandwidth2,...
    iterations2);

Ybaseline = Y2;

end