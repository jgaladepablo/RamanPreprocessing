function PlotPCAScores(ax,...
    PCAResults,...
    Classes,...
    ClassNames,...
    PCX,...
    PCY)

cla(ax)

Colours = lines(length(ClassNames));

hold(ax,'on')

for i = 1:length(ClassNames)

    ClassIndex = ...
        strcmp(Classes,ClassNames{i});

    scatter(ax,...
        PCAResults.score(ClassIndex,PCX),...
        PCAResults.score(ClassIndex,PCY),...
        20,...
        Colours(i,:),...
        'filled')

end

hold(ax,'off')

xlabel(ax,...
    sprintf('PC%d Score',PCX))

ylabel(ax,...
    sprintf('PC%d Score',PCY))

legend(ax,...
    ClassNames,...
    'Location','best')

grid(ax,'on')

end